#!/usr/bin/env python3
"""Generate multi-window, multi-burn-rate SLO rules from slo/*.yaml.

Outputs, per spec:
  observability/rules/<service>-slo.rules.yml               plain Prometheus rule file (local stack, promtool)
  platform/observability/slo/<service>-prometheusrule.yaml  PrometheusRule CRD (kube-prometheus-stack)

Burn-rate policy (Google SRE Workbook, "Alerting on SLOs", table 5-8):
  page   : 14.4x over 1h AND 5m   -> 2% of the 30d budget gone in 1h
  page   : 6x    over 6h AND 30m  -> 5% gone in 6h
  ticket : 3x    over 1d AND 2h   -> 10% gone in 1d
  ticket : 1x    over 3d AND 6h   -> 10% gone in 3d

Usage: generate_slo_rules.py [--check]
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d", "30d"]
BURN_POLICY = [
    # (severity, factor, long window, short window)
    ("page", 14.4, "1h", "5m"),
    ("page", 6, "6h", "30m"),
    ("ticket", 3, "1d", "2h"),
    ("ticket", 1, "3d", "6h"),
]
HEADER = "# GENERATED by scripts/generate_slo_rules.py from {src} - DO NOT EDIT.\n"


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):  # no &id001 anchors in generated YAML
        return True


def _str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def _one_line(expr: str) -> str:
    return " ".join(expr.split())


def build_groups(spec: dict) -> list[dict]:
    service = spec["service"]
    groups = []
    for slo in spec["slos"]:
        name, objective = slo["name"], float(slo["objective"])
        budget = round(1 - objective, 6)
        sel = f'service="{service}",slo="{name}"'
        labels = {"service": service, "slo": name}

        recording = [{"record": "slo:objective:ratio", "expr": f"vector({objective})", "labels": labels}]
        for w in WINDOWS:
            errors = _one_line(slo["sli"]["errors"]).replace("{{window}}", w)
            total = _one_line(slo["sli"]["total"]).replace("{{window}}", w)
            recording.append({"record": f"slo:sli_error:ratio_rate{w}", "expr": f"({errors})\n/\n({total})", "labels": labels})
        recording += [
            {
                "record": "slo:burn_rate:ratio_rate1h",
                "expr": f"slo:sli_error:ratio_rate1h{{{sel}}} / {budget}",
                "labels": labels,
            },
            {
                "record": "slo:error_budget_remaining:ratio",
                "expr": f"1 - (slo:sli_error:ratio_rate30d{{{sel}}} / {budget})",
                "labels": labels,
            },
        ]
        groups.append({"name": f"slo-recording-{service}-{name}", "interval": "30s", "rules": recording})

        alerts = []
        for severity, speed in (("page", "Fast"), ("ticket", "Slow")):
            clauses = []
            for sev, factor, long_w, short_w in BURN_POLICY:
                if sev != severity:
                    continue
                threshold = round(factor * budget, 6)
                clauses.append(
                    f"(slo:sli_error:ratio_rate{long_w}{{{sel}}} > {threshold}"
                    f" and slo:sli_error:ratio_rate{short_w}{{{sel}}} > {threshold})"
                )
            alerts.append(
                {
                    "alert": f"{slo['alert_prefix']}BudgetBurn{speed}",
                    "expr": "\nor\n".join(clauses),
                    "labels": {**labels, "severity": severity, "team": spec.get("owner", "unowned")},
                    "annotations": {
                        "summary": f"{service} is burning its {name} error budget too fast ({severity})",
                        "description": f"{slo['description']} Current error ratio over the long window: "
                        "{{ $value | humanizePercentage }}.",
                        "runbook_url": f"https://github.com/JoshilFernandes/sentinel-slo-platform/blob/main/{slo['runbook']}",
                        "runbook_hint": f"{name} error budget burn",
                    },
                }
            )
        groups.append({"name": f"slo-alerts-{service}-{name}", "rules": alerts})
    return groups


def render(spec_path: Path) -> dict[Path, str]:
    spec = yaml.safe_load(spec_path.read_text())
    groups = build_groups(spec)
    rel = spec_path.relative_to(ROOT)
    service = spec["service"]
    plain = HEADER.format(src=rel) + yaml.dump({"groups": groups}, Dumper=_Dumper, sort_keys=False, width=200)
    crd = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": f"{service}-slo",
            "namespace": "monitoring",
            "labels": {"release": "kube-prometheus-stack", "app.kubernetes.io/part-of": "sentinel"},
        },
        "spec": {"groups": groups},
    }
    crd_text = HEADER.format(src=rel) + yaml.dump(crd, Dumper=_Dumper, sort_keys=False, width=200)
    return {
        ROOT / "observability" / "rules" / f"{service}-slo.rules.yml": plain,
        ROOT / "platform" / "observability" / "slo" / f"{service}-prometheusrule.yaml": crd_text,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()
    drift = False
    for spec_path in sorted((ROOT / "slo").glob("*.yaml")):
        for out, text in render(spec_path).items():
            current = out.read_text() if out.exists() else ""
            if args.check:
                if current != text:
                    drift = True
                    sys.stdout.writelines(
                        difflib.unified_diff(current.splitlines(True), text.splitlines(True), str(out), "generated")
                    )
            else:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(text)
                print(f"wrote {out.relative_to(ROOT)}")
    if drift:
        print("\nSLO rules are out of date: run `make slo` and commit the result.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
